import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildScreenRequest, filterRows, gencoIndex, gencoSummary } from '../src/solver/screening.js';

const genco = JSON.parse(readFileSync(new URL('../src/data/screening_case118_ieee_autores.json', import.meta.url)));      // modelo principal
const n10 = JSON.parse(readFileSync(new URL('../src/data/screening_case118_ieee_n10.json', import.meta.url)));            // our training, for comparison

test('request uses the case name when it exists, otherwise the tables', () => {
    assert.deepEqual(buildScreenRequest({ gridName: 'case118_ieee', mpc: {} }), { scope: 'both', grid: 'case118_ieee' });
    assert.deepEqual(buildScreenRequest({ gridName: null, mpc: { a: 1 } }, 'lines'), { scope: 'lines', case: { a: 1 } });
});

test('contingency list filters', () => {
    const data = { contingencies: [
        { type: 'line', id: 1, needsAction: true }, { type: 'bus', id: 2, needsAction: true }, { type: 'line', id: 3, needsAction: false },
    ] };
    assert.equal(filterRows(data).length, 2);
    assert.equal(filterRows(data, { onlyAction: false }).length, 3);
    assert.deepEqual(filterRows(data, { onlyAction: false, kind: 'line' }).map(c => c.id), [1, 3]);
    assert.deepEqual(filterRows(null), []);
    const rep = { contingencies: [{ type: 'line', id: 1, needsAction: true, hasPlan: true }, { type: 'line', id: 2, needsAction: true, hasPlan: false }] };
    assert.deepEqual(filterRows(rep, { onlyReady: true }).map(c => c.id), [1]);
    assert.equal(filterRows(rep).length, 2);
    assert.equal(filterRows(data, { onlyReady: true }).length, 2, 'without hasPlan (live backend) everything counts as available');
});

test('GENCO summary matches the file generated by the validation', () => {
    const g = gencoSummary(genco);
    assert.equal(g.scenarios, genco.scenarios);
    assert.ok(g.maeGenco < g.maeDc, 'GENCO must have a smaller mean error than the DC');
    assert.ok(g.recall90.genco > g.recall90.dc);
    assert.equal(gencoSummary(null), null);
    assert.equal(gencoIndex(genco).size, genco.lines.length);
});

test('main model = authors checkpoint; our N-10 and the reduced one are kept for comparison', () => {
    const reduzido = JSON.parse(readFileSync(new URL('../src/data/screening_case118_ieee_reduzido.json', import.meta.url)));
    const p = gencoSummary(genco);
    const a = gencoSummary(n10);
    const r = gencoSummary(reduzido);
    assert.match(p.model, /authors/);
    assert.match(a.model, /N-10/);
    assert.match(r.model, /reduced/);
    assert.ok(p.maeGenco < a.maeGenco && a.maeGenco < 1.0 && r.maeGenco > 2.0, 'mean error: authors < N-10 (< 1 point) < reduced (> 2)');
    assert.ok(p.maeGenco < 0.2, 'the authors checkpoint errs by about 0.1 point');
    assert.ok(a.recall100.genco >= 50 && r.recall100.genco < 30, 'detection at 100%: 52% (N-10) vs 25% (reduced)');
    assert.ok(p.recall100.genco >= a.recall100.genco);
    assert.ok(p.recall90.genco >= 99 && a.recall90.genco >= 98);
    assert.equal(p.scenarios, 177); assert.equal(a.scenarios, 177);
    assert.equal(a.scenarioRecall.genco, 99);
});
